import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { expect, test } from '@playwright/test';

const portrait = join(process.cwd(), 'tests/fixtures/obama-portrait.jpg');
const portraitData = `data:image/jpeg;base64,${readFileSync(portrait).toString('base64')}`;
test('no-login student and admin: saved photo, real face check-in, editable period ranges', async ({ page, baseURL }) => {
  test.setTimeout(120_000);
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript((dataUrl) => {
    Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: { getUserMedia: async () => {
      const image = new Image(); image.src = dataUrl; await image.decode();
      const canvas = document.createElement('canvas'); canvas.width = image.naturalWidth; canvas.height = image.naturalHeight;
      canvas.getContext('2d')!.drawImage(image, 0, 0); return canvas.captureStream(15);
    } } });
  }, portraitData);
  await page.goto('/');
  const db = new DatabaseSync(process.env.ADMIN_E2E_DB_PATH!);
  db.prepare('DELETE FROM attendance_records WHERE user_id = ?').run('prototype-student');
  db.close();
  await expect(page.getByRole('heading', { name: 'Good to see you.' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Student', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Admin', exact: true })).toBeVisible();
  await page.route('**/api/linways/details', async (route) => {
    expect(route.request().postDataJSON()).toEqual({ email: 'demo@example.com', password: 'test-password' });
    await route.fulfill({ json: { source: 'Linways', fetchedAt: Date.now(), profile: { summary: { name: 'Demo Student', rollNo: 'DEMO001', programme: 'Artificial Intelligence', currentSem: '3' }, sections: [{ title: 'Personal information', fields: [{ label: 'Date of birth', value: '11 May 2006' }, { label: 'Gender', value: null }] }, { title: 'Contact information', fields: [{ label: 'Email', value: 'demo@example.com' }] }], notes: [] } } });
  });
  await page.getByRole('button', { name: 'View student details' }).click();
  await page.getByLabel('Linways email').fill('demo@example.com');
  await page.getByLabel('Linways password').fill('test-password');
  const firstProfileOpened = page.waitForEvent('popup');
  await page.getByRole('button', { name: 'Fetch student details', exact: true }).click();
  const firstProfile = await firstProfileOpened;
  await expect(firstProfile.getByRole('heading', { name: 'Demo Student', exact: true })).toBeVisible();
  await expect(firstProfile.getByText('Not provided', { exact: true }).first()).toBeVisible();
  for (const width of [320, 768, 1024, 1440]) {
    await firstProfile.setViewportSize({ width, height: 900 });
    expect(await firstProfile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await firstProfile.screenshot({ path: test.info().outputPath('profile.png'), fullPage: true });
  await firstProfile.close();
  await expect(page.getByLabel('Linways password')).toHaveValue('');
  await page.getByRole('button', { name: 'Close details' }).click();
  const initial = await (await page.request.get('/api/prototype')).json();
  const day = new Intl.DateTimeFormat('en-US', { timeZone: initial.timezone, weekday: 'long' }).format(new Date());
  const weekday = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'].indexOf(day);
  const ranges = [['00:00', '00:01'], ['00:01', '23:00'], ['23:00', '23:10'], ['23:10', '23:20'], ['23:20', '23:30'], ['23:30', '23:40'], ['23:40', '23:59']];
  const rows = initial.timetable.filter((row: { weekday: number }) => row.weekday === weekday);
  expect(rows).toHaveLength(7);
  expect((await page.request.put('/api/prototype', { headers: { Origin: baseURL! }, data: { weekday, periods: rows.map((row: { id: number }, index: number) => ({ id: row.id, name: `Prototype period ${index + 1}`, startTime: ranges[index][0], endTime: ranges[index][1] })) } })).ok()).toBe(true);
  await page.request.delete('/api/prototype', { headers: { Origin: baseURL! } });
  await page.reload();
  await page.getByLabel('Choose your photo').setInputFiles(join(process.cwd(), 'tests/fixtures/blank.png'));
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Save photo', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'No face found' })).toBeVisible({ timeout: 30_000 });
  await page.getByLabel('Choose your photo').setInputFiles(portrait);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Save photo', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Photo saved', { timeout: 30_000 });
  await page.reload();
  await expect(page.getByAltText('Your saved attendance photo')).toBeVisible();
  expect(await page.getByAltText('Your saved attendance photo').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
  await page.getByRole('link', { name: 'Admin', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Make time for learning.' })).toBeVisible();
  await page.getByLabel('Timetable weekday').selectOption(String(weekday));
  await page.getByLabel('Period 2 name', { exact: true }).fill('Physics');
  await page.getByLabel('Period 2 end time', { exact: true }).fill('22:59');
  await page.getByRole('button', { name: 'Save seven periods' }).click();
  await expect(page.getByRole('status')).toContainText('Seven periods saved');
  await page.screenshot({ path: test.info().outputPath('admin.png'), fullPage: true });
  await page.getByRole('link', { name: 'Student', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Physics', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Start camera' }).click();
  await expect(page.getByRole('button', { name: 'Mark present', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Mark present', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Present marked for Physics', { timeout: 30_000 });
  await page.reload();
  await expect(page.getByRole('button', { name: 'Already present' })).toBeDisabled();
  await page.screenshot({ path: test.info().outputPath('student.png'), fullPage: true });
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await page.getByRole('button', { name: 'Start camera' }).click();
  await expect(page.getByRole('button', { name: 'Stop camera' })).toBeVisible();
  await page.getByLabel('Choose a replacement photo').setInputFiles(portrait);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'View student details' }).click();
  await page.getByLabel('Linways email').fill('demo@example.com');
  await page.getByLabel('Linways password').fill('test-password');
  const resetProfileOpened = page.waitForEvent('popup');
  await page.getByRole('button', { name: 'Fetch student details', exact: true }).click();
  const resetProfile = await resetProfileOpened;
  await expect(resetProfile.getByRole('heading', { name: 'Demo Student', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Reset student' }).click();
  await expect(page.getByRole('status')).toContainText('Student reset');
  await expect(page.getByAltText('Your saved attendance photo')).toHaveCount(0);
  await expect(page.getByAltText('Selected photo, not saved yet')).toHaveCount(0);
  await expect(page.getByRole('checkbox')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Start camera' })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Already present' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Save photo', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'View student details' })).toHaveAttribute('aria-expanded', 'false');
  await expect(resetProfile.getByRole('heading', { name: 'Profile cleared.' })).toBeVisible();
  await expect(resetProfile.getByText('Demo Student', { exact: true })).toHaveCount(0);
  await resetProfile.close();
  await page.reload();
  await expect(page.getByLabel('Choose your photo')).toBeVisible();
  const reset = await (await page.request.get('/api/prototype')).json();
  expect(reset).toMatchObject({ enrolled: false, photoSavedAt: null });
  expect(reset.periods.every((row: { recordedAt: number | null }) => row.recordedAt === null)).toBe(true);
  expect((await page.request.get('/api/prototype?photo=1')).status()).toBe(404);
  expect(reset.timetable.find((row: { id: number }) => row.id === rows[1].id)?.name).toBe('Physics');
  expect(errors).toEqual([]);
});
